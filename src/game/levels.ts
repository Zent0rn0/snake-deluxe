export function levelPar(level: LevelDef): [number, number] {
  if (level.par) return level.par;
  const k = level.stepMs / 130;
  return [Math.round(level.goal * 2.6 * k), Math.round(level.goal * 1.75 * k)];
}

export function starsFor(level: LevelDef, seconds: number): number {
  const [two, three] = levelPar(level);
  return seconds <= three ? 3 : seconds <= two ? 2 : 1;
}
